"""Sample every core source once and write docs/data_sources.md.

Live network script: run by hand (`fantasy-rag verify-sources`), never in CI.
Findings record shapes and counts only; no league IDs, usernames or owner names
are written, because the repo is public.
"""

import importlib.metadata
import json
import re
import time
from datetime import UTC, date, datetime
from pathlib import Path
from typing import Any

import httpx
import nflreadpy as nfl
import polars as pl

from fantasy_rag.config import REPO_ROOT, Settings

SLEEPER = "https://api.sleeper.app/v1"
USER_AGENT = "fantasy-rag/0.1 (+https://github.com/NgoBenny/fantasy-rag)"
SKILL_POSITIONS = {"QB", "RB", "WR", "TE", "K"}
GSIS_RE = re.compile(r"^00-\d{7}$")

Facts = dict[str, Any]


# ---------- pure helpers (unit tested) ----------


def null_rate(df: pl.DataFrame, col: str) -> float | None:
    """Share of null or blank values in `col`; None if the column is missing."""
    if col not in df.columns or df.height == 0:
        return None
    s = df[col]
    blank = s.is_null()
    if s.dtype == pl.String:
        blank = blank | (s.str.strip_chars() == "")
    return round(int(blank.sum()) / df.height, 4)


def max_of(df: pl.DataFrame, col: str) -> Any:
    return df[col].max() if col in df.columns else None


def top_values(df: pl.DataFrame, col: str, n: int = 8) -> dict[str, int]:
    if col not in df.columns:
        return {}
    counts = df[col].value_counts(sort=True).head(n)
    return {str(row[0]): int(row[1]) for row in counts.iter_rows()}


def describe(df: pl.DataFrame, **facts: Any) -> Facts:
    return {"rows": df.height, **facts, "columns": df.columns}


def render(sections: list[tuple[str, Facts]], gaps: list[str], meta: Facts) -> str:
    lines = [
        "# Data sources: verified findings",
        "",
        "Generated by `uv run fantasy-rag verify-sources`. Do not edit by hand.",
        "",
        *[f"- **{k}**: {v}" for k, v in meta.items()],
        "",
        "## Gaps vs PLAN.md",
        "",
        *([f"- {g}" for g in gaps] or ["- None found."]),
        "",
    ]
    for title, facts in sections:
        lines += [f"## {title}", "", "| Fact | Value |", "| --- | --- |"]
        columns = facts.get("columns")
        for key, value in facts.items():
            if key != "columns":
                lines.append(f"| {key} | {_cell(value)} |")
        if columns is not None:
            lines += [
                "",
                f"<details><summary>{len(columns)} columns</summary>",
                "",
                ", ".join(f"`{c}`" for c in columns),
                "",
                "</details>",
            ]
        lines.append("")
    return "\n".join(lines)


def _cell(value: Any) -> str:
    if isinstance(value, dict | list):
        return json.dumps(value, default=str).replace("|", "\\|")
    return str(value)


# ---------- nflverse ----------


def check_nflverse(
    season: int,
) -> tuple[list[tuple[str, Facts]], list[str], pl.DataFrame, set[str]]:
    sections: list[tuple[str, Facts]] = []
    gaps: list[str] = []

    players = nfl.load_players()
    sections.append(
        (
            "nflreadpy load_players()",
            describe(
                players,
                gsis_id_null_rate=null_rate(players, "gsis_id"),
                status_values=top_values(players, "status"),
            ),
        )
    )

    ids = nfl.load_ff_playerids()
    id_cols = ["gsis_id", "sleeper_id", "espn_id", "pfr_id", "fantasypros_id"]
    sleeper_ids = ids["sleeper_id"].drop_nulls()
    sections.append(
        (
            "nflreadpy load_ff_playerids() (ID crosswalk)",
            describe(
                ids,
                null_rates={c: null_rate(ids, c) for c in id_cols},
                duplicate_sleeper_ids=sleeper_ids.len() - sleeper_ids.n_unique(),
            ),
        )
    )

    sched = nfl.load_schedules([season])
    played = sched.filter(pl.col("result").is_not_null())
    sections.append(
        (
            f"nflreadpy load_schedules([{season}])",
            describe(
                sched,
                newest_completed_week=max_of(played, "week"),
                newest_completed_gameday=max_of(played, "gameday"),
                gametime_sample=sched["gametime"].drop_nulls().head(3).to_list(),
                null_rates={c: null_rate(sched, c) for c in ["spread_line", "total_line", "roof"]},
            ),
        )
    )
    gaps.append(
        "schedules: `gameday` + `gametime` are local US/Eastern strings, not a timestamp. "
        "`kickoff_at` must be built with an explicit America/New_York zone."
    )

    stats = nfl.load_player_stats([season])
    stats_week = max_of(stats, "week")
    gsis_share = stats["player_id"].drop_nulls().str.contains(GSIS_RE.pattern).mean()
    sections.append(
        (
            f"nflreadpy load_player_stats([{season}]) (weekly)",
            describe(
                stats,
                max_week=stats_week,
                player_id_gsis_format_share=gsis_share,
                season_types=top_values(stats, "season_type"),
            ),
        )
    )

    snaps = nfl.load_snap_counts([season])
    sections.append(
        (
            f"nflreadpy load_snap_counts([{season}])",
            describe(snaps, max_week=max_of(snaps, "week"), has_gsis_id="gsis_id" in snaps.columns),
        )
    )
    if "gsis_id" not in snaps.columns and "player_id" not in snaps.columns:
        gaps.append(
            "snap_counts: keyed by `pfr_player_id` only (no GSIS ID). "
            "Map through `player_external_ids` (provider=pfr) from ff_playerids."
        )

    for yr in (2024, season):
        depth = nfl.load_depth_charts([yr])
        facts = describe(
            depth,
            has_week="week" in depth.columns,
            has_dt="dt" in depth.columns,
            dt_min=depth["dt"].min() if "dt" in depth.columns else None,
            dt_max=max_of(depth, "dt"),
            distinct_dt=depth["dt"].n_unique() if "dt" in depth.columns else None,
            gsis_id_null_rate=null_rate(depth, "gsis_id"),
        )
        sections.append((f"nflreadpy load_depth_charts([{yr}])", facts))
        if yr >= 2025 and "week" not in depth.columns:
            gaps.append(
                f"depth_charts {yr}: no `week` column; rows are snapshots stamped by `dt`. "
                "PLAN's (season, week, ...) key does not apply from 2025 on."
            )

    opp = nfl.load_ff_opportunity([season])
    opp_week = max_of(opp, "week")
    sections.append(
        (
            f"nflreadpy load_ff_opportunity([{season}])",
            describe(
                opp,
                max_week=opp_week,
                weeks_behind_player_stats=(stats_week - opp_week)
                if stats_week is not None and opp_week is not None
                else None,
            ),
        )
    )

    ranks = nfl.load_ff_rankings("week")
    sections.append(
        (
            'nflreadpy load_ff_rankings("week")',
            describe(
                ranks, newest_scrape_date=max_of(ranks, "scrape_date"), id_column="fantasypros_id"
            ),
        )
    )

    for yr in (2024, 2025, season):
        inj = nfl.load_injuries([yr])
        has_dm = "date_modified" in inj.columns
        sections.append(
            (
                f"nflreadpy load_injuries([{yr}])",
                describe(
                    inj,
                    max_week=max_of(inj, "week"),
                    has_date_modified=has_dm,
                    date_modified_null_rate=null_rate(inj, "date_modified"),
                    gsis_id_null_rate=null_rate(inj, "gsis_id"),
                    report_status=top_values(inj, "report_status"),
                    practice_status=top_values(inj, "practice_status"),
                ),
            )
        )
        if not has_dm:
            gaps.append(
                f"injuries {yr}: `date_modified` column is absent. Rows cannot prove what was "
                "known before kickoff; rely on our own `injury_snapshots`."
            )

    stat_gsis = set(
        stats.filter(pl.col("position").is_in(list(SKILL_POSITIONS)))["player_id"]
        .drop_nulls()
        .to_list()
    )
    return sections, gaps, ids, stat_gsis


# ---------- Sleeper ----------


class Sleeper:
    def __init__(self) -> None:
        self.client = httpx.Client(base_url=SLEEPER, headers={"User-Agent": USER_AGENT}, timeout=60)

    def get(self, path: str, **params: Any) -> Any:
        time.sleep(0.25)  # far under Sleeper's 1,000 calls/minute
        resp = self.client.get(path, params=params)
        resp.raise_for_status()
        return resp.json()

    def players(self, cache_dir: Path) -> dict[str, Facts]:
        """/players/nfl at most once per day: reuse today's cached copy if present."""
        cache = cache_dir / f"sleeper_players_{date.today().isoformat()}.json"
        if cache.exists():
            data: dict[str, Facts] = json.loads(cache.read_text(encoding="utf-8"))
            return data
        data = self.get("/players/nfl")
        cache_dir.mkdir(parents=True, exist_ok=True)
        cache.write_text(json.dumps(data), encoding="utf-8")
        return data


def summarize_sleeper_players(
    players: dict[str, Facts], crosswalk: pl.DataFrame, stat_gsis: set[str]
) -> tuple[Facts, list[str]]:
    """`stat_gsis`: GSIS IDs of skill players with stats this season (the IDs that matter)."""
    gaps: list[str] = []
    active = [
        p
        for p in players.values()
        if p.get("active") and p.get("team") and p.get("position") in SKILL_POSITIONS
    ]
    n = len(active) or 1

    def filled(key: str) -> int:
        return sum(1 for p in active if str(p.get(key) or "").strip())

    cw = {
        str(r[0]): (r[1] or "").strip()
        for r in crosswalk.select("sleeper_id", "gsis_id").drop_nulls("sleeper_id").iter_rows()
    }
    in_cw = [p for p in active if str(p.get("player_id")) in cw]
    both = [p for p in in_cw if str(p.get("gsis_id") or "").strip() and cw[str(p["player_id"])]]
    disagree = sum(1 for p in both if str(p["gsis_id"]).strip() != cw[str(p["player_id"])])

    # Which stat players can be linked to a Sleeper ID, by each route and by either.
    via_cw = {g for g in cw.values() if g}
    via_sleeper = {str(p.get("gsis_id") or "").strip() for p in players.values()} - {""}
    n_stat = len(stat_gsis) or 1

    def share(found: set[str]) -> str:
        hit = len(stat_gsis & found)
        return f"{hit} of {len(stat_gsis)} ({hit / n_stat:.1%})"

    facts: Facts = {
        "total_players": len(players),
        "active_skill_players_on_a_team (QB/RB/WR/TE/K)": len(active),
        "active_skill_with_gsis_id": f"{filled('gsis_id')} ({filled('gsis_id') / n:.1%})",
        "active_skill_with_espn_id": f"{filled('espn_id')} ({filled('espn_id') / n:.1%})",
        "active_skill_in_ff_playerids_crosswalk": f"{len(in_cw)} ({len(in_cw) / n:.1%})",
        "sleeper_gsis_vs_crosswalk_gsis_disagreements": f"{disagree} of {len(both)}",
        "stat_players_linked_via_crosswalk": share(via_cw),
        "stat_players_linked_via_sleeper_gsis_id": share(via_sleeper),
        "stat_players_linked_via_either": share(via_cw | via_sleeper),
        "injury_status_non_null": filled("injury_status"),
        "injury_status_values": _counts(active, "injury_status"),
        "practice_participation_non_null": filled("practice_participation"),
        "practice_participation_values": _counts(active, "practice_participation"),
        "injury_body_part_non_null": filled("injury_body_part"),
        "depth_chart_order_non_null": filled("depth_chart_order"),
        "fields": sorted({k for p in players.values() for k in p}),
    }
    unlinked = len(stat_gsis - via_cw - via_sleeper)
    if unlinked:
        gaps.append(
            f"{unlinked} skill players with stats this season have no Sleeper ID by either route "
            "(crosswalk or Sleeper `gsis_id`); they must be reported as unresolved."
        )
    if filled("practice_participation") == 0:
        gaps.append(
            "Sleeper `practice_participation` is empty for every active skill player. "
            "Practice status must come from the nflverse injury file (snapshot it ourselves)."
        )
    return facts, gaps


def _counts(rows: list[Facts], key: str) -> dict[str, int]:
    out: dict[str, int] = {}
    for r in rows:
        if v := r.get(key):
            out[str(v)] = out.get(str(v), 0) + 1
    return dict(sorted(out.items(), key=lambda kv: -kv[1]))


def check_league_shapes(api: Sleeper, username: str, season: str, week: int) -> list[Facts]:
    """Shape-only league findings: nothing identifying is returned."""
    user = api.get(f"/user/{username}")
    if not user:
        return [{"error": "username not found"}]
    leagues = api.get(f"/user/{user['user_id']}/leagues/nfl/{season}") or []
    out: list[Facts] = []
    for lg in leagues:
        league = api.get(f"/league/{lg['league_id']}")
        rosters = api.get(f"/league/{lg['league_id']}/rosters") or []
        matchups = api.get(f"/league/{lg['league_id']}/matchups/{week}") or []
        scoring = league.get("scoring_settings") or {}
        out.append(
            {
                "status": league.get("status"),
                "total_rosters": league.get("total_rosters"),
                "roster_positions": league.get("roster_positions"),
                "scoring_settings_key_count": len(scoring),
                "scoring_rec": scoring.get("rec"),
                "idp_or_bonus_keys": sorted(k for k in scoring if k.startswith(("idp_", "bonus_"))),
                "scoring_settings_keys": sorted(scoring),
                "roster_fields": sorted({k for r in rosters for k in r}),
                "matchup_fields": sorted({k for m in matchups for k in m}),
                f"matchups_week_{week}_with_points": sum(
                    1 for m in matchups if m.get("points") is not None
                ),
            }
        )
    return out


# ---------- entry point ----------


def run() -> Path:
    settings = Settings()
    started = datetime.now(UTC)
    season = int(nfl.get_current_season())
    sections, gaps, crosswalk, stat_gsis = check_nflverse(season)

    api = Sleeper()
    state = api.get("/state/nfl")
    sections.insert(0, ("Sleeper /state/nfl", {k: state.get(k) for k in sorted(state)}))
    stats_week = next(f["max_week"] for t, f in sections if "load_player_stats" in t)
    if stats_week is not None and int(state["week"]) - 1 != int(stats_week):
        gaps.append(
            f"Sleeper week is {state['week']} but nflverse weekly stats end at week {stats_week} "
            "(expected one week behind)."
        )

    sleeper_facts, sleeper_gaps = summarize_sleeper_players(
        api.players(REPO_ROOT / "data" / "cache"), crosswalk, stat_gsis
    )
    sections.insert(1, ("Sleeper /players/nfl (active skill players)", sleeper_facts))
    gaps += sleeper_gaps

    trending = api.get("/players/nfl/trending/add", lookback_hours=24, limit=25)
    sections.insert(
        2,
        (
            "Sleeper /players/nfl/trending/add (24h, limit 25)",
            {"rows": len(trending), "fields": sorted({k for t in trending for k in t})},
        ),
    )

    if settings.sleeper_username:
        for i, facts in enumerate(
            check_league_shapes(
                api, settings.sleeper_username, str(state["season"]), state["week"]
            ),
            start=1,
        ):
            sections.insert(2 + i, (f"Sleeper league {i} (shape only)", facts))

    meta = {
        "Run at (UTC)": started.isoformat(timespec="seconds"),
        "nflreadpy": importlib.metadata.version("nflreadpy"),
        "Season checked": season,
        "nflreadpy current week": nfl.get_current_week(),
    }
    out = REPO_ROOT / "docs" / "data_sources.md"
    out.write_text(render(sections, gaps, meta), encoding="utf-8", newline="\n")
    return out
